"""Generate design/assets/Map/indonesia-map.fragment.html (SVG land + city pins).
Run: python scripts/build-map-svg.py
Land: geoBoundaries IDN ADM0 simplified (ODbL, OpenStreetMap contributors). Cities: content/seed/cities.json.
"""
import json, os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = os.path.join(root, "design/assets/Map/indonesia-main-rings.geo.json")
if not os.path.exists(src):
    raise SystemExit("map source missing: " + src)
g = json.load(open(src, encoding="utf8"))
cities = json.load(open(os.path.join(root, "content/seed/cities.json"), encoding="utf8"))
feats = g["features"] if "features" in g else [g]
rings = []
for f in feats:
    geo = f["geometry"]
    polys = geo["coordinates"] if geo["type"] == "MultiPolygon" else [geo["coordinates"]]
    rings += [p[0] for p in polys]
def bbox_area(r):
    xs = [p[0] for p in r]; ys = [p[1] for p in r]
    return (max(xs) - min(xs)) * (max(ys) - min(ys))
rings = [r for r in rings if bbox_area(r) > 0.02]
xs = [x for r in rings for x, y in r]; ys = [y for r in rings for x, y in r]
minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)
W, padl, padr, padt, padb = 1000, 24, 90, 30, 30
sx = (W - padl - padr) / (maxx - minx); H = int((maxy - miny) * sx + padt + padb)
def P(x, y): return (padl + (x - minx) * sx, padt + (maxy - y) * sx)
paths = []
for r in rings:
    pts = [P(x, y) for x, y in r]; out = [pts[0]]
    for p in pts[1:]:
        if abs(p[0] - out[-1][0]) + abs(p[1] - out[-1][1]) > 1.2: out.append(p)
    paths.append("M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in out) + "Z")
land = f'<path class="af-map__land" d="{" ".join(paths)}"/>'
# label anchor, dx, dy per city (tuned by eye on the 1000px viewBox)
place = {
    "Medan": ("start", 12, -4), "Pekanbaru": ("end", -12, 4), "Batam": ("start", 12, 4),
    "Padang": ("end", -12, 4), "Palembang": ("end", -12, 4), "Lampung": ("end", -12, 10),
    "Jakarta": ("start", 10, -10), "Bandung": ("middle", 0, 22), "Semarang": ("start", 8, -10),
    "Yogyakarta": ("middle", 16, 22), "Balikpapan": ("start", 12, -4), "Makassar": ("start", 12, 10),
    "Jayapura": ("end", -12, -8),
}
pins = []
for c in cities:
    x, y = P(c["lng"], c["lat"]); n = c["name"]; a, dx, dy = place.get(n, ("start", 12, 4))
    pins.append(f'<g><circle class="af-map__pin" cx="{x:.1f}" cy="{y:.1f}" r="8"/><circle class="af-map__pin-core" cx="{x:.1f}" cy="{y:.1f}" r="3.5"/>'
                f'<text class="af-map__label" x="{x+dx:.1f}" y="{y+dy:.1f}" text-anchor="{a}">{n}</text></g>')
svg = (f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="Affirmate network: {len(cities)} cities across Indonesia" '
       f'xmlns="http://www.w3.org/2000/svg">{land}{"".join(pins)}</svg>')
out = os.path.join(root, "design/assets/Map/indonesia-map.fragment.html")
open(out, "w", encoding="utf8").write(svg)
print("written", out, W, H, len(rings), "rings", len(svg), "bytes")

# Also emit the land path as a TypeScript module for the Next.js NetworkMap component (pins come from the CMS).
ts = os.path.join(root, "src/lib/indonesia-land.ts")
open(ts, "w", encoding="utf8").write(
    "// Generated by scripts/build-map-svg.py from design/assets/Map/indonesia-main-rings.geo.json. Do not edit.\n"
    "// Land: geoBoundaries IDN ADM0 (ODbL, OpenStreetMap contributors). Equirectangular, padded viewBox.\n"
    f"export const MAP = {{ width: {W}, height: {H}, minx: {minx}, maxy: {maxy}, scale: {sx}, padl: {padl}, padt: {padt} }} as const\n"
    "export const project = (lng: number, lat: number) => ({ x: MAP.padl + (lng - MAP.minx) * MAP.scale, y: MAP.padt + (MAP.maxy - lat) * MAP.scale })\n"
)
print("written", ts)

# Public land-only SVG (cream fill baked in) so the HTML does not inline ~100 KB of path data.
pub = os.path.join(root, "public/brand/indonesia-land.svg")
open(pub, "w", encoding="utf8").write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}"><path fill="#f7f5ee" fill-opacity=".96" d="{" ".join(paths)}"/></svg>')
print("written", pub)
