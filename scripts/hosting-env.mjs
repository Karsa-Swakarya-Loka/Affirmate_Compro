// Writes the production .env for the cPanel hosting (Hostinger, tatakelola.affirmate.co.id) when none exists.
// Secrets are generated here, on the server, so they never travel through chat or git. Safe to re-run: an
// existing .env is left untouched. Fill SMTP_* in that file afterwards for the contact form (OPEN-QUESTIONS #10).
import { existsSync, writeFileSync } from 'node:fs'
import { randomBytes } from 'node:crypto'

const site = process.env.SITE_URL || 'https://tatakelola.affirmate.co.id'
if (existsSync('.env')) {
  console.log('.env already exists, nothing written')
} else {
  writeFileSync('.env', [
    '# Generated by scripts/hosting-env.mjs on ' + new Date().toISOString(),
    'DATABASE_ADAPTER=sqlite',
    'DATABASE_URI=file:./.data/affirmate.db',
    'MEDIA_DIR=media',
    'PAYLOAD_SECRET=' + randomBytes(32).toString('hex'),
    'PREVIEW_SECRET=' + randomBytes(24).toString('hex'),
    'NEXT_PUBLIC_SITE_URL=' + site,
    'SMTP_HOST=', 'SMTP_PORT=465', 'SMTP_SECURE=true', 'SMTP_USER=', 'SMTP_PASS=',
    'SMTP_FROM_ADDRESS=', 'SMTP_FROM_NAME=Affirmate Administrative', 'INQUIRY_RECIPIENTS=info@affirmate.co.id',
    'SEED_OVERWRITE=false', '',
  ].join('\n'))
  console.log('.env written for', site)
}
